package com.bluemalic.repair.service;

/**
 * 租户账号配额（阶段 5 · ADR-020）。
 *
 * <p>只做一件事：在**建号之前**确认这个租户还有位置。把校验收在这里而不是散在
 * 学生 / 维修工两个 Service 里，是因为"算配额"的规则必须只有一份——否则一边按
 * 启用中的账号算、一边按全部账号算，超限的时机就会不一致。
 *
 * <p><b>计数口径</b>：`deleted = 0` 的全部账号（**含已停用**）。停用不是删除——
 * 它随时可能被重新启用，把停用当作"空出位置"会让重新启用时悄悄超限。要让出位置就删账号
 * （本项目没有删除账号的接口，账号生命周期是"停用"）。
 *
 * <p><b>为什么不做并发强一致</b>：两个管理员同时建号时，可能各自读到"还有一个位置"，
 * 最后超一两个。为一个管理员手工操作的场景去加分布式锁不值得；批量导入是单请求、天然的窗口，
 * 那里会把整批一起校验（不会出现"导入 500 个只按 1 个校验"的问题）。超出一两个的后果
 * 也可接受——配额是保护性的软上限，不是计费凭证。
 */
public interface TenantQuotaService {

    /**
     * 确认还能再建 {@code adding} 个学生账号，不能就抛 {@code 30004}。
     *
     * @param adding 本次要新建的数量（单个建号传 1，批量导入传整批数量）
     */
    void requireStudentSeats(long tenantId, int adding);

    /** 同上，维修工。 */
    void requireWorkerSeats(long tenantId, int adding);
}
