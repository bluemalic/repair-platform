-- ============================================================
-- V2 · 学生账号管理：加「首次登录需改密」标记
-- ============================================================
--
-- 背景：后勤批量建学生账号时，只能给一个**统一初始口令**（口令要写在纸上发给学生，
-- 一人一个反而没人记得住）。而学号在班级里是公开信息，统一口令意味着同学之间可以互相登录。
-- 所以初始口令必须是一次性的：首登强制改成自己的密码。
--
-- 为什么不用"密码字段是否为初始值"来判断（那种免加列的做法）：
--   判断"当前密码还是不是初始口令"要靠把初始口令和库里的哈希做一次 BCrypt 比对，
--   而初始口令一旦允许管理员自定义，这个判断就变成了"拿配置里的口令去试"——
--   口令一改、规则一变，判断就失效，而且每次登录都要多跑一次 BCrypt。
--   一个显式的列把这件事说清楚，也让"哪些账号还没改密"可以直接查。
--
-- 为什么不改变 SysUser 之外的任何东西：校验这个标记的拦截器只读 Sa-Token Session
-- 里的一份标记（登录时写入），所以没有引入每请求一次的查库。
-- ============================================================

ALTER TABLE `sys_user`
    ADD COLUMN `must_change_password` tinyint NOT NULL DEFAULT 0
        COMMENT '是否需强制改密 0否 1是（管理员建的账号为 1，改密成功后置 0）'
        AFTER `status`;
