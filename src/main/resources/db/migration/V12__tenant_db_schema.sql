-- ============================================================
-- V12 · 租户库名（每租户一个 database，阶段 6 · ADR-021）
-- ============================================================
--
-- 这一列回答一个问题：**这个学校的数据在哪个库里**。
--   · `NULL` = 存量租户：数据还在平台库（`repair`）里，走默认数据源。过渡期里这是正常状态；
--   · 有值   = 这个学校已经搬到自己的库（新开的学校开通时就有值）。
--
-- 【为什么不复用 id 拼库名，而要显式存一列】
--   ① 可读：运维要能看着库名就知道是哪个学校（`repair_gdou` 一眼认得出，雪花 id 认不出）；
--   ② 可演算：将来要"迁到另一台实例 / 换一套命名"时，改的是这一列，不是重新推导的规则；
--   ③ 可查询：`SELECT ... WHERE db_schema IS NULL` 就是"还没搬的学校"这份待办清单本身。
--
-- 【为什么库名带 uk 唯一索引】
--   学校编码允许连字符（`a-b`），建库时替换成下划线（`a_b`），于是 `a-b` 与 `a_b` 会撞成同一个库名。
--   撞了必须**报错**而不是静默共用（两个学校写同一个库 = 最严重的串租户）。唯一索引是那个兜底：
--   开通接口会先查一次给出人话文案，索引负责并发下的最后一道。
--
-- 【存量租户怎么办】
--   全为 NULL，行为与改动前完全一致（走平台库的默认数据源）。搬迁与切换是阶段 6 的第 2、3 步，
--   计划是"建库 → 分批搬 → 校验 → 改这一列 → 观察"（ADR-021 决定 7）。
-- ============================================================

ALTER TABLE `tenant`
    ADD COLUMN `db_schema` varchar(64) DEFAULT NULL
        COMMENT '租户库名，NULL=存量（数据在平台库）' AFTER `code`,
    ADD UNIQUE KEY `uk_db_schema` (`db_schema`);
