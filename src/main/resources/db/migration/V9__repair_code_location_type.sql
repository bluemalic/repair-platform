-- ============================================================
-- V9 · 报修码区分「宿舍房间」与「公共区域」（docs/01 §4.6）
-- ============================================================
--
-- 背景：报修码原来是"每间房一张"，解决的是位置输入的准确性。但公共区域（走廊、楼梯间、
-- 公共卫生间、图书馆大厅）不可能"一间房一码"，而**到场核验**又必须有一张码可扫——
-- 所以加这一列，让公共区域也能有一张"区域码"（一个区域一张，贴在必经之处）。
--
-- 两个语义约定：
--   · `location_type = 1`（默认）：宿舍房间，`room` 是房间号，如 `3-412`
--   · `location_type = 2`：公共区域，`room` **存区域名**，如 `1F-大厅`、`3F-走廊`
--
-- 为什么不是"公共区域不要码"：维修工到场要扫同一张码、服务端校验码与工单位置一致
-- （`arrive` 的既有逻辑），没有码就没有到场凭据。**每个可报修的位置都必须有一张码**——
-- 这条不变量让"扫码 / 手动选位置"两条入口共用同一套到场核验，不必为公共区域写特判。
--
-- 已有数据全部默认为 1（宿舍房间），不需要回填。
-- ============================================================

ALTER TABLE `repair_code`
    ADD COLUMN `location_type` tinyint NOT NULL DEFAULT 1 COMMENT '1 宿舍房间 / 2 公共区域' AFTER `room`;
