package com.bluemalic.repair.service;

/**
 * 演示数据重置：把公网演示站恢复成"刚部署完的样子"。
 *
 * <p><b>要解决的问题</b>：演示站是公开的、访客拿着公开口令就能进管理端改数据。放任几天，
 * 楼栋会被删、类别会被停用、工单列表会被垃圾数据塞满，HR 或面试官点开看到的是一片狼藉。
 * 手动重置靠不住（没人会记得做），所以做成定时任务 + 一次性可手动触发的服务。
 *
 * <p><b>重置什么、不重置什么</b>：
 * <ul>
 *   <li>重置：工单 / 流转日志 / 评价 / 站内通知（业务数据）、演示账号的口令（有人改过密码也能恢复）、
 *       对象存储里的图片（删了工单，图片就没有引用方了）</li>
 *   <li>不动：楼栋 / 类别 / 报修码 / 租户（基础数据）——它们被改坏的概率低，
 *       而重建它们要牵连 repair_code 的"一房一码"规则，收益不抵风险</li>
 * </ul>
 *
 * <p>整个重置在一个事务里完成；对象存储的清理放在事务之外（它不是数据库资源，
 * 清理失败也不该把已重置的数据回滚——图片清理失败最多是占点磁盘）。
 */
public interface DemoResetService {

    /** 本次重置做了哪些事，用于日志与测试断言。 */
    record Result(int deletedTickets, int createdTickets, int createdAccounts, int purgedObjects) {
    }

    Result reset();
}
