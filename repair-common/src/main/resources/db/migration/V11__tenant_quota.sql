-- ============================================================
-- V11 · 租户级账号配额（阶段 5 · ADR-020）
-- ============================================================
--
-- 背景：多租户共用一套部署时，"某个学校批量导入五千个学生"会拖垮所有人的库。
-- 配额是最便宜的一道闸：平台运营开通学校时给一个上限，建号时校验。
--
-- 为什么是**账号数**，不是"工单数 / 存储量"：
--   · 账号数是学校规模的最直接代理，且**计数是 O(1) 的索引查询**（`idx_tenant_type`）；
--   · 工单数/存储量是流量型配额，更适合用限流与对象存储配额做，且要实时统计，成本高得多。
--     "批量导入"这一下才是真正会把库撑坏的动作，它正好被账号配额挡住（ADR-020）。
--
-- `0` 表示**不限**：不设上限也是合法选择（例如平台自用租户）。
-- 旧数据全部按默认值走（一所学校 200 名学生 / 20 名维修工，够用且不会挡住演示）。
-- ============================================================

ALTER TABLE `tenant`
    ADD COLUMN `max_students` int NOT NULL DEFAULT 200 COMMENT '学生账号上限（0 = 不限）' AFTER `phone`,
    ADD COLUMN `max_workers` int NOT NULL DEFAULT 20 COMMENT '维修工账号上限（0 = 不限）' AFTER `max_students`;
