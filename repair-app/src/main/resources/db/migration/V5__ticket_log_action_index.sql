-- ============================================================
-- V5 · 给 ticket_log 补一条 (action, ticket_id) 索引
-- ============================================================
--
-- 背景：压测发现的（docs/08）。看板核心指标卡里的"超时工单数"口径是
-- 「ticket_log 里出现过 ACCEPT_TIMEOUT / PROCESS_TIMEOUT / AUTO_CLOSE」，
-- 而 ticket_log 上原本只有 (ticket_id, create_time) 这一条索引——
-- 也就是**只能从工单侧去找动作**。于是"找出全部超时工单"只能逐个工单去探（2 万单 ≈ 2 万次探测），
-- 看板 100 QPS 时 P50 606ms、只能跑到 64 QPS。
--
-- 反过来从动作侧找：超时动作在真实数据里是**稀有事件**（正常学校一天也就几条），
-- 一条 (action, ticket_id) 索引把"所有超时动作"变成一次很小的范围扫描，
-- 再回表按租户与时间区间过滤——同口径、代价从 O(工单数) 降到 O(超时数)。
--
-- 这条索引还顺带服务"按动作查流转记录"这类排障查询（比如"哪些工单被自动关闭过"）。
--
-- 注意：统计口径**没有变**（仍然以 ticket_log 的动作为准、不在 SQL 里重算阈值），
-- 变的只是取数路径；StatisticsTest 里对 timeoutCount 的断言就是这条改动的守卫。
-- ============================================================

ALTER TABLE `ticket_log`
    ADD INDEX `idx_action_ticket` (`action`, `ticket_id`);
