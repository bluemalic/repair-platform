-- ============================================================
-- V7 · 让 audit_log.target_type 可空（登录事件没有"目标"）
-- ============================================================
--
-- 背景：登录事件入审计（docs/01 §4.4）。审计的六样里有一项是"对谁（目标类型 + id + 名称快照）"，
-- 而**登录没有作用对象**——它没有改任何东西，被登录的那个账号本身已经记在操作人列上了。
--
-- 为什么不是"给登录事件随便填一个目标类型"：
--   填 ACCOUNT 会让每一行都出现"操作人 = 张三 / 目标 = 账号 张三"，读起来像数据错了；
--   而 target_id / target_name 本来就是可空的（"批量导入"这类没有单一目标的动作已经在用 NULL），
--   只有 target_type 被写成 NOT NULL——那是当初只考虑"写操作"时留下的约束，不是有意的设计。
--
-- 放宽约束是安全的方向：不改任何已有数据、不重写表（MySQL 8 的 MODIFY 对 varchar 放宽 NULL 是原地改元数据）。
-- 已有的记录全都是写操作，仍然带着目标类型；查询侧没有任何变化（列表本来就不按 target_type 过滤）。
-- ============================================================

ALTER TABLE `audit_log`
    MODIFY COLUMN `target_type` varchar(32) DEFAULT NULL
        COMMENT '目标类型：WORKER / STUDENT / BUILDING / CATEGORY / REPAIR_CODE / TENANT / ACCOUNT；登录事件没有目标，为 NULL';
